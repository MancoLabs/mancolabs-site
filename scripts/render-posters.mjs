// Renders the hero poster (light/dark, desktop/phone) and the social share image
// from the real 3D scene, so the poster-to-3D crossfade lines up frame for frame.
// Usage: npm run posters   (builds the site first; needs Chrome with a working GPU)
import { chromium } from 'playwright-core';
import { build, preview } from 'vite';
import sharp from 'sharp';
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';

const OUT = 'src/assets/hero';
const PORT = 4179;

const SHAPES = [
  { name: 'desktop', viewport: { width: 1440, height: 900 }, scale: 2, widths: [960, 1600, 2400] },
  { name: 'mobile', viewport: { width: 390, height: 844 }, scale: 3, widths: [430, 780, 1170] },
];
const SCHEMES = ['light', 'dark'];

await build({ logLevel: 'warn' });
const server = await preview({ preview: { port: PORT, strictPort: true }, logLevel: 'warn' });
const base = `http://localhost:${PORT}`;
const browser = await chromium.launch({ channel: 'chrome' });
await mkdir(OUT, { recursive: true });

async function open(viewport, scale, scheme, query) {
  const ctx = await browser.newContext({ viewport, deviceScaleFactor: scale, colorScheme: scheme });
  const page = await ctx.newPage();
  await page.goto(`${base}/${query}`, { waitUntil: 'load' });
  await page.waitForFunction(() => document.documentElement.dataset.posterReady === 'true', null, { timeout: 30000 });
  await page.waitForTimeout(600);
  return { ctx, page };
}

const sizes = {};
for (const scheme of SCHEMES) {
  for (const shape of SHAPES) {
    const { ctx, page } = await open(shape.viewport, shape.scale, scheme, '?poster');
    await page.addStyleTag({ content: '.site-header,.hero-inner,.hero-stage,.tilt-toggle{visibility:hidden!important}' });
    const clip = await page.evaluate(() => {
      const r = document.querySelector('.hero').getBoundingClientRect();
      return { x: r.left, y: r.top, width: r.width, height: r.height };
    });
    const png = await page.screenshot({ clip });
    sizes[shape.name] = { width: Math.round(clip.width), height: Math.round(clip.height) };
    for (const w of shape.widths) {
      const file = path.join(OUT, `poster-${scheme}-${shape.name}-${w}`);
      const img = sharp(png).resize({ width: w });
      await img.clone().avif({ quality: 50, effort: 7 }).toFile(`${file}.avif`);
      await img.clone().webp({ quality: 72 }).toFile(`${file}.webp`);
    }
    await ctx.close();
    console.log(`poster ${scheme}/${shape.name}`);
  }
}

// Social share image: the hero scene with the headline, 1200x630.
{
  const { ctx, page } = await open({ width: 1200, height: 630 }, 2, 'light', '?og');
  const png = await page.screenshot();
  await sharp(png).resize({ width: 1200 }).jpeg({ quality: 84, mozjpeg: true }).toFile('public/og.jpg');
  await ctx.close();
  console.log('og.jpg');
}

await browser.close();
server.httpServer.close();

// The <picture> markup the home page includes.
const srcset = (scheme, shape, ext) =>
  SHAPES.find((s) => s.name === shape).widths.map((w) => `/src/assets/hero/poster-${scheme}-${shape}-${w}.${ext} ${w}w`).join(', ');
const source = (media, scheme, shape) =>
  ['avif', 'webp']
    .map((ext) => `  <source${media ? ` media="${media}"` : ''} type="image/${ext}" srcset="${srcset(scheme, shape, ext)}" sizes="100vw">`)
    .join('\n');
const narrow = '(max-aspect-ratio: 4/5)';
const dark = '(prefers-color-scheme: dark)';
const { width, height } = sizes.desktop;
const html = `<!-- Generated by scripts/render-posters.mjs. Run \`npm run posters\` to rebuild. -->
<picture class="hero-poster">
${source(`${dark} and ${narrow}`, 'dark', 'mobile')}
${source(dark, 'dark', 'desktop')}
${source(narrow, 'light', 'mobile')}
${source('', 'light', 'desktop')}
  <img src="/src/assets/hero/poster-light-desktop-1600.webp" srcset="${srcset('light', 'desktop', 'webp')}" sizes="100vw" alt="" width="${width}" height="${height}" fetchpriority="high" decoding="async">
</picture>
`;
await writeFile('partials/hero-poster.html', html);
console.log('wrote partials/hero-poster.html');
