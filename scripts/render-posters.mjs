// Renders the hero posters and the social share image from the real 3D scene,
// so the poster-to-3D crossfade lines up frame for frame.
//   desktop: the whole hero          -> partials/hero-poster.html
//   phones:  the paper band only     -> partials/hero-band-poster.html
//   share:   1200x630 with headline  -> public/og.jpg
// Usage: npm run posters   (builds the site first; needs Chrome with a working GPU)
import { chromium } from 'playwright-core';
import { build, preview } from 'vite';
import sharp from 'sharp';
import { mkdir, writeFile, readdir, unlink } from 'node:fs/promises';
import path from 'node:path';

const OUT = 'src/assets/hero';
const PORT = 4179;
const BLANK = 'data:image/gif;base64,R0lGODlhAQABAIAAAAAAAP///yH5BAEAAAAALAAAAAABAAEAAAIBRAA7';
const PHONE = '(max-width: 699px)';
const DARK = '(prefers-color-scheme: dark)';

const SHAPES = [
  { name: 'desktop', viewport: { width: 1440, height: 900 }, scale: 2, widths: [960, 1600, 2400], target: '.hero' },
  { name: 'band', viewport: { width: 390, height: 844 }, scale: 3, widths: [390, 780, 1170], target: '.hero-band' },
];
const SCHEMES = ['light', 'dark'];

await build({ logLevel: 'warn' });
const server = await preview({ preview: { port: PORT, strictPort: true }, logLevel: 'warn' });
const base = `http://localhost:${PORT}`;
const browser = await chromium.launch({ channel: 'chrome' });
await mkdir(OUT, { recursive: true });
for (const f of await readdir(OUT)) if (f.startsWith('poster-') || f.startsWith('band-')) await unlink(path.join(OUT, f));

async function open(viewport, scale, scheme, query) {
  const ctx = await browser.newContext({ viewport, deviceScaleFactor: scale, colorScheme: scheme });
  const page = await ctx.newPage();
  await page.goto(`${base}/${query}`, { waitUntil: 'load' });
  await page.waitForFunction(() => document.documentElement.dataset.posterReady === 'true', null, { timeout: 30000 });
  await page.waitForTimeout(600);
  return { ctx, page };
}

const sizes = {};
for (const scheme of SCHEMES) {
  for (const shape of SHAPES) {
    const { ctx, page } = await open(shape.viewport, shape.scale, scheme, '?poster');
    await page.addStyleTag({ content: '.site-header,.hero-inner,.hero-stage,.band-poster{visibility:hidden!important}' });
    const clip = await page.evaluate((sel) => {
      const r = document.querySelector(sel).getBoundingClientRect();
      return { x: Math.max(0, r.left), y: r.top, width: Math.min(r.width, innerWidth), height: r.height };
    }, shape.target);
    const png = await page.screenshot({ clip });
    sizes[shape.name] = { width: Math.round(clip.width), height: Math.round(clip.height) };
    const prefix = shape.name === 'band' ? 'band' : 'poster';
    for (const w of shape.widths) {
      const file = path.join(OUT, `${prefix}-${scheme}-${w}`);
      const img = sharp(png).resize({ width: w });
      await img.clone().avif({ quality: 50, effort: 7 }).toFile(`${file}.avif`);
      await img.clone().webp({ quality: 72 }).toFile(`${file}.webp`);
    }
    await ctx.close();
    console.log(`${prefix} ${scheme}`);
  }
}

// Social share image: the hero scene with the headline, 1200x630.
{
  const { ctx, page } = await open({ width: 1200, height: 630 }, 2, 'light', '?og');
  const png = await page.screenshot();
  await sharp(png).resize({ width: 1200 }).jpeg({ quality: 84, mozjpeg: true }).toFile('public/og.jpg');
  await ctx.close();
  console.log('og.jpg');
}

await browser.close();
server.httpServer.close();

const srcset = (prefix, scheme, widths, ext) => widths.map((w) => `/src/assets/hero/${prefix}-${scheme}-${w}.${ext} ${w}w`).join(', ');
const sources = (media, prefix, scheme, widths, sizesAttr) =>
  ['avif', 'webp']
    .map((ext) => `  <source${media ? ` media="${media}"` : ''} type="image/${ext}" srcset="${srcset(prefix, scheme, widths, ext)}" sizes="${sizesAttr}">`)
    .join('\n');
const header = '<!-- Generated by scripts/render-posters.mjs. Run `npm run posters` to rebuild. -->';
const [desk, band] = SHAPES;

// Desktop poster: phones get a 1-pixel placeholder so they never download it.
await writeFile('partials/hero-poster.html', `${header}
<picture class="hero-poster">
  <source media="${PHONE}" srcset="${BLANK}">
${sources(DARK, 'poster', 'dark', desk.widths, '100vw')}
${sources('', 'poster', 'light', desk.widths, '100vw')}
  <img src="/src/assets/hero/poster-light-1600.webp" srcset="${srcset('poster', 'light', desk.widths, 'webp')}" sizes="100vw" alt="" width="${sizes.desktop.width}" height="${sizes.desktop.height}" fetchpriority="high" decoding="async">
</picture>
`);

// Phone band poster: wider screens get the placeholder instead.
await writeFile('partials/hero-band-poster.html', `${header}
<picture class="band-poster">
  <source media="(min-width: 700px)" srcset="${BLANK}">
${sources(DARK, 'band', 'dark', band.widths, '100vw')}
${sources('', 'band', 'light', band.widths, '100vw')}
  <img src="/src/assets/hero/band-light-780.webp" srcset="${srcset('band', 'light', band.widths, 'webp')}" sizes="100vw" alt="" width="${sizes.band.width}" height="${sizes.band.height}" decoding="async">
</picture>
`);
console.log('wrote partials/hero-poster.html and partials/hero-band-poster.html');
